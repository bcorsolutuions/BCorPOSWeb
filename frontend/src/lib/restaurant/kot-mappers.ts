/** One order line being built/edited on the table-order screen, before it's saved as a KOT. */
export interface DraftOrderLine {
  draftId: string;
  id?: string | null;
  rowID?: number | null;
  menuCode: string;
  menuName: string;
  unitCode?: string | null;
  kitchenCode?: string | null;
  rate: number;
  qty: number;
  modifiers: SelectedModifier[];
  courseNo?: number | null;
  courseName?: string | null;
  preparationNotes?: string | null;

  // Combo Items — set on every draft line generated by tapping a combo tile
  // (see buildComboDraftLines). Lines sharing a comboInstanceId came from
  // one "add combo" action; exactly one of them (comboCode set) is the
  // priced bill line, the rest are zero-rated kitchen-only tickets for a
  // real component that needs its own KOT (see kotToCartLines' grouping).
  comboInstanceId?: string | null;
  comboCode?: string | null;
  comboComponents?: ResolvedComboComponent[];

  // Set Menu — same shape/rationale as the combo fields above, plus the
  // course identity a Set Menu's kitchen-sibling lines carry that Combo's
  // never did (see KOTDetails.cs's doc comment on these columns).
  setMenuInstanceId?: string | null;
  setMenuCode?: string | null;
  setMenuComponents?: ResolvedSetMenuComponent[];
  setMenuGroupCode?: string | null;
  setMenuGroupSequence?: number | null;

  // Open Item Billing — a one-off charge rung against the shared generic
  // OPENITEM menu/inventory code (menuCode) instead of a permanent master
  // record per description. approvedBy is stamped once the manager-
  // approval dialog succeeds (see open-item-entry-dialog.tsx); the backend
  // independently re-verifies it server-side regardless (never trusted at
  // face value — see KOTController/PosController's ValidateOpenItemLinesAsync).
  isOpenItem?: boolean;
  openItemDescription?: string | null;
  openItemRemarks?: string | null;
  approvedBy?: string | null;
  approvedOn?: string | null;
}

export function newDraftId(): string {
  return newUuid();
}

export function kotDetailToDraftLine(d: KotDetailDto): DraftOrderLine {
  let modifiers: SelectedModifier[] = [];
  if (d.modifiersJson) {
    try {
      modifiers = JSON.parse(d.modifiersJson);
    } catch {
      modifiers = [];
    }
  }
  let comboComponents: ResolvedComboComponent[] | undefined;
  if (d.comboComponentsJson) {
    try {
      comboComponents = JSON.parse(d.comboComponentsJson);
    } catch {
      comboComponents = undefined;
    }
  }
  let setMenuComponents: ResolvedSetMenuComponent[] | undefined;
  if (d.setMenuComponentsJson) {
    try {
      setMenuComponents = JSON.parse(d.setMenuComponentsJson);
    } catch {
      setMenuComponents = undefined;
    }
  }
  return {
    draftId: newDraftId(),
    id: d.id,
    rowID: d.rowID,
    menuCode: d.menuCode,
    menuName: d.menuName ?? d.menuCode,
    unitCode: d.unitCode,
    kitchenCode: d.kitchenCode,
    rate: d.rate,
    qty: d.qty,
    modifiers,
    courseNo: d.courseNo,
    courseName: d.courseName,
    preparationNotes: d.preparationNotes,
    comboInstanceId: d.comboInstanceId,
    comboCode: d.comboCode,
    comboComponents,
    setMenuInstanceId: d.setMenuInstanceId,
    setMenuCode: d.setMenuCode,
    setMenuComponents,
    setMenuGroupCode: d.setMenuGroupCode,
    setMenuGroupSequence: d.setMenuGroupSequence,
    isOpenItem: d.isOpenItem,
    openItemDescription: d.openItemDescription,
    openItemRemarks: d.openItemRemarks,
    approvedBy: d.approvedBy,
    approvedOn: d.approvedOn,
  };
}

/**
 * Tapping a combo tile in the restaurant table-order flow inserts one priced
 * carrier line (bills at the fixed combo price, no kitchen ticket of its
 * own) plus one zero-rated kitchen-ticket line per SELECTED component that
 * has a kitchenCode (a plain Inventory/Service component with nothing to
 * prepare gets no KOT line — its stock is still consumed at settle time from
 * the priced line's comboComponents snapshot, see lib/pos/combo-consume.ts).
 * All lines share one comboInstanceId so kotToCartLines can collapse them
 * back into ONE bill line later.
 */
export function buildComboDraftLines(
  combo: ComboMasterDto,
  resolvedComponents: ResolvedComboComponent[],
  quantity: number,
): Omit<DraftOrderLine, "draftId">[] {
  const comboInstanceId = newDraftId();
  const additionalTotal = resolvedComponents.filter((c) => c.selected).reduce((sum, c) => sum + (c.additionalPrice || 0), 0);

  const pricedLine: Omit<DraftOrderLine, "draftId"> = {
    menuCode: combo.menuCode || combo.code,
    menuName: combo.comboName,
    kitchenCode: null,
    rate: combo.sellingPrice + additionalTotal,
    qty: quantity,
    modifiers: [],
    comboInstanceId,
    comboCode: combo.code,
    comboComponents: resolvedComponents,
  };

  const kitchenLines: Omit<DraftOrderLine, "draftId">[] = resolvedComponents
    .filter((c) => c.selected && c.kitchenCode)
    .map((c) => ({
      menuCode: c.code,
      menuName: c.name,
      unitCode: c.unitCode ?? undefined,
      kitchenCode: c.kitchenCode,
      rate: 0,
      qty: c.qty * quantity,
      modifiers: [],
      comboInstanceId,
    }));

  return [pricedLine, ...kitchenLines];
}

/**
 * Same shape as buildComboDraftLines above (one priced carrier + one
 * zero-rated kitchen line per selected choice with a kitchenCode), but each
 * kitchen line also carries setMenuGroupCode/setMenuGroupSequence — unlike
 * Combo, a Set Menu's kitchen ticket needs to show which course a line
 * belongs to (§9 — "STARTER: Soup"), and the sequence rides along so a
 * future course-firing feature has it to sort/hold on without re-deriving
 * it from the master later (§10).
 */
export function buildSetMenuDraftLines(
  setMenu: SetMenuMasterDto,
  resolvedComponents: ResolvedSetMenuComponent[],
  quantity: number,
): Omit<DraftOrderLine, "draftId">[] {
  const setMenuInstanceId = newDraftId();
  const additionalTotal = resolvedComponents.filter((c) => c.selected).reduce((sum, c) => sum + (c.additionalPrice || 0), 0);

  const pricedLine: Omit<DraftOrderLine, "draftId"> = {
    menuCode: setMenu.menuCode || setMenu.code,
    menuName: setMenu.setMenuName,
    kitchenCode: null,
    rate: setMenu.sellingPrice + additionalTotal,
    qty: quantity,
    modifiers: [],
    setMenuInstanceId,
    setMenuCode: setMenu.code,
    setMenuComponents: resolvedComponents,
  };

  const kitchenLines: Omit<DraftOrderLine, "draftId">[] = resolvedComponents
    .filter((c) => c.selected && c.kitchenCode)
    .map((c) => ({
      menuCode: c.code,
      menuName: c.name,
      unitCode: c.unitCode ?? undefined,
      kitchenCode: c.kitchenCode,
      rate: 0,
      qty: c.qty * quantity,
      modifiers: [],
      setMenuInstanceId,
      setMenuGroupCode: c.groupCode,
      setMenuGroupSequence: c.groupSequence,
    }));

  return [pricedLine, ...kitchenLines];
}

/**
 * Groups draft lines sharing a comboInstanceId/setMenuInstanceId (see
 * buildComboDraftLines/buildSetMenuDraftLines above) into one bundle each —
 * used by OrderCart to render one parent+children card per bundle instead of
 * flat zero-rated sibling rows, and by SplitTableDialog to offer one
 * move-quantity control per bundle instead of per raw KOT line. A line with
 * no instance id is its own singleton group.
 */
export function groupDraftLines(lines: DraftOrderLine[]): DraftOrderLine[][] {
  const groups = new Map<string, DraftOrderLine[]>();
  for (const line of lines) {
    const key = line.comboInstanceId ?? line.setMenuInstanceId ?? line.draftId;
    const list = groups.get(key) ?? [];
    list.push(line);
    groups.set(key, list);
  }
  return Array.from(groups.values());
}

export interface SplitTableMove {
  detailId: string;
  qty: number;
}

/**
 * Expands a chosen "move N of this bundle" quantity per group — one row for
 * a plain item, one course-firing line per selected Set Menu/Combo course
 * for a bundle — into the exact per-KOTDetails-row quantities
 * RestaurantOperationsController's /tables/{code}/split endpoint needs.
 * A Combo/Set Menu's "quantity" is bundle count and every sibling line's own
 * qty is already componentQty * bundleQty (see buildSetMenuDraftLines/
 * buildComboDraftLines), so every line in the group scales by the same
 * fraction of the bundle being moved; a plain (ungrouped) line has only
 * itself in its group, so the fraction reduces to the qty moved directly.
 * Lines with no `id` haven't been saved to the KOT yet (still-local drafts)
 * and are skipped — there's nothing on the server to move for them yet.
 */
export function buildSplitTableMoves(groups: DraftOrderLine[][], moveByGroupKey: Record<string, number>): SplitTableMove[] {
  const moves: SplitTableMove[] = [];
  for (const group of groups) {
    const priced = group.find((l) => l.comboCode || l.setMenuCode) ?? group[0];
    if (!priced) continue;
    const key = priced.comboInstanceId ?? priced.setMenuInstanceId ?? priced.draftId;
    const moveQty = moveByGroupKey[key];
    if (!moveQty || moveQty <= 0) continue;
    const bundleQty = priced.qty;
    for (const line of group) {
      if (!line.id) continue;
      const rowMoveQty = round((line.qty * moveQty) / bundleQty);
      if (rowMoveQty > 0) moves.push({ detailId: line.id, qty: rowMoveQty });
    }
  }
  return moves;
}

function modifierTotal(line: DraftOrderLine): number {
  return line.modifiers.reduce((sum, m) => sum + m.price, 0);
}

export function draftLineTotals(line: DraftOrderLine) {
  const modifierAmount = round(modifierTotal(line) * line.qty);
  const grossAmount = round(line.rate * line.qty + modifierAmount);
  return { grossAmount, modifierAmount, netAmount: grossAmount };
}

