/**
 * Builds the UpdatePosDto to save a held bill's tenders (status stays "Held")
 * or complete it (status "Completed") — lines are carried over unchanged;
 * omitting id/rowID on each detail/payment row makes the backend replace the
 * whole collection rather than trying to diff it (see UpdatePosDetDto's
 * doc-comment in types/pos.ts).
 */
export function buildHeldBillUpdateDto(pos: PosDto, payments: PosPayment[], status: PosStatus): UpdatePosDto {
  const paidAmount = payments.reduce((sum, p) => sum + p.amount, 0);
  return {
    docDt: pos.docDt,
    custCode: pos.custCode,
    custName: pos.custName,
    salesManCode: pos.salesManCode,
    terminalID: pos.terminalID,
    shiftNo: pos.shiftNo,
    tableCode: pos.tableCode,
    tabCode: pos.tabCode,
    floorCode: pos.floorCode,
    sectionCode: pos.sectionCode,
    orderTypeCode: pos.orderTypeCode,
    diningTypeCode: pos.diningTypeCode,
    waiterCode: pos.waiterCode,
    captainCode: pos.captainCode,
    guestCount: pos.guestCount,
    kotDocNo: pos.kotDocNo,
    status,
    subTotal: pos.subTotal,
    discountPercentage: pos.discountPercentage,
    discountAmount: pos.discountAmount,
    totalDiscAmountPer: pos.totalDiscAmountPer,
    taxAmount: pos.taxAmount,
    additionalCharge: pos.additionalCharge,
    roundingAmount: pos.roundingAmount,
    netTotal: pos.netTotal,
    paidAmount,
    balanceAmount: Math.max(0, pos.netTotal - paidAmount),
    changeAmount: Math.max(0, paidAmount - pos.netTotal),
    promotionCode: pos.promotionCode,
    promotionDiscountAmount: pos.promotionDiscountAmount,
    couponCode: pos.couponCode,
    couponDiscountAmount: pos.couponDiscountAmount,
    isSO: pos.isSO,
    salesReturn: pos.salesReturn,
    billType: pos.billType,
    soRefNo: pos.soRefNo,
    remarks: pos.remarks,
    details: pos.details.map(posDetToUpdateDetail),
    paymentDetails: payments.map(paymentToDetailDto),
    serviceDetails: pos.serviceDetails.map(posServiceDetToUpdateDetail),
  };
}
