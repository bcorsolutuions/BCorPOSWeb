/**
 * Converts an open KOT's lines into POS cart lines so the bill can be
 * settled with the existing POS totals/payment machinery. Lines sharing a
 * comboInstanceId (see buildComboDraftLines) collapse into ONE cart line,
 * sourced off the group's priced row (comboCode set) — the zero-rated
 * kitchen-only sibling rows never become their own bill line, only kitchen
 * history. A line with no comboInstanceId is its own singleton group,
 * exactly today's 1:1 behavior.
 */
export function kotToCartLines(kot: KotDto): PosCartLine[] {
  const active = kot.details.filter((d) => !d.cancelled);
  const groups = new Map<string, KotDetailDto[]>();
  for (const d of active) {
    const key = d.comboInstanceId ?? d.setMenuInstanceId ?? d.id;
    const list = groups.get(key) ?? [];
    list.push(d);
    groups.set(key, list);
  }

  const lines: PosCartLine[] = [];
  for (const group of groups.values()) {
    const priced = group.find((d) => d.comboCode) ?? group.find((d) => d.setMenuCode) ?? group[0];
    if (!priced) continue;
    let comboComponents: ResolvedComboComponent[] | undefined;
    if (priced.comboComponentsJson) {
      try {
        comboComponents = JSON.parse(priced.comboComponentsJson);
      } catch {
        comboComponents = undefined;
      }
    }
    let setMenuComponents: ResolvedSetMenuComponent[] | undefined;
    if (priced.setMenuComponentsJson) {
      try {
        setMenuComponents = JSON.parse(priced.setMenuComponentsJson);
      } catch {
        setMenuComponents = undefined;
      }
    }
    lines.push({
      lineId: priced.id,
      lineType: priced.comboCode ? "Combo" : priced.setMenuCode ? "SetMenu" : undefined,
      itemCode: priced.comboCode ?? priced.setMenuCode ?? priced.menuCode,
      name: priced.menuName ?? priced.menuCode,
      unitCode: priced.unitCode,
      unitPrice: priced.rate + (priced.qty > 0 ? priced.modifierAmount / priced.qty : 0),
      quantity: priced.qty,
      discountPerc: 0,
      discountAmt: priced.discountAmount,
      taxCode: null,
      taxPercentage: priced.qty > 0 && priced.rate > 0 ? round((priced.taxAmount / (priced.rate * priced.qty)) * 100) : 0,
      costAmount: 0,
      comboCode: priced.comboCode,
      comboComponents,
      setMenuCode: priced.setMenuCode,
      setMenuComponents,
      isOpenItem: priced.isOpenItem,
      openItemDescription: priced.openItemDescription,
      openItemRemarks: priced.openItemRemarks,
      approvedBy: priced.approvedBy,
    });
  }
  return lines;
}

/**
 * One PosCartLine -> one detail row. Looks up the source KOT line by id
 * (kotToCartLines sets lineId = the KOT detail's own id) rather than by
 * array position, so this is safe to call with any subset/reordering of a
 * KOT's lines — not just the full, original-order set (needed for Split
 * Bill, where each split only carries a fraction of the KOT's lines).
 */
function detailFromCartLine(kot: KotDto, line: PosCartLine): CreatePosDetDto {
  const t = calcLineTotals(line);
  const kotLine = kot.details.find((d) => d.id === line.lineId);
  return {
    itemCode: line.itemCode,
    name: line.name,
    unitCode: line.unitCode,
    unitPrice: line.unitPrice,
    quantity: line.quantity,
    weighingQuantity: 0,
    grossAmount: t.gross,
    discountPerc: 0,
    discountAmt: t.discount,
    // Promotion Engine isn't wired into the restaurant/KOT flow — these
    // lines never carry a promotion, only a manual discount.
    promotionCode: null,
    promotionDiscountAmount: 0,
    comboCode: line.comboCode ?? null,
    comboComponentsJson: line.comboComponents ? JSON.stringify(line.comboComponents) : null,
    setMenuCode: line.setMenuCode ?? null,
    setMenuComponentsJson: line.setMenuComponents ? JSON.stringify(line.setMenuComponents) : null,
    isOpenItem: line.isOpenItem ?? false,
    openItemDescription: line.openItemDescription ?? null,
    openItemRemarks: line.openItemRemarks ?? null,
    approvedBy: line.approvedBy ?? null,
    amount: t.gross - t.discount,
    taxPercentage: line.taxPercentage,
    taxAmount: t.tax,
    netAmount: t.net,
    iac: 0,
    costAmount: 0,
    kotDocNo: kot.docNo,
    kotRowID: kotLine?.rowID,
  };
}

function paymentToDetailDto(p: PosPayment) {
  return {
    type: p.type,
    paymentModeCode: p.type.toUpperCase(),
    curRate: 1,
    amount: p.amount,
    foreignAmount: 0,
    refCode: p.refCode ?? null,
    cardType: p.type === "Card" ? "Card" : null,
    cardLastFourDigits: p.cardLastFourDigits ?? null,
    authorizationCode: p.authorizationCode ?? null,
  };
}

/**
 * Shared header/payments assembly for any bill built off a table's KOT —
 * a plain settle, a held bill, or one split of a Split Bill. Doesn't reuse
 * buildCreatePosDto (lib/pos/mappers.ts) because that contract has no room
 * for table/order-type/dining-type/waiter/captain/KOT linkage — those are
 * restaurant-only concerns, kept out of the shared POS builder rather than
 * growing its input shape for a case plain retail sales never hit.
 */
function assemblePosDto(input: {
  kot: KotDto;
  details: CreatePosDetDto[];
  totals: { subTotal: number; discountAmount: number; taxAmount: number; netTotal: number };
  payments: PosPayment[];
  terminalId: string;
  shiftNo?: number | null;
  status: PosStatus;
}): CreatePosDto {
  const paidAmount = input.payments.reduce((sum, p) => sum + p.amount, 0);
  return {
    docDt: new Date().toISOString(),
    custCode: input.kot.customerCode,
    custName: input.kot.customerName,
    terminalID: input.terminalId,
    shiftNo: input.shiftNo ?? input.kot.shiftNo,
    tableCode: input.kot.tableCode,
    tabCode: input.kot.tabCode,
    floorCode: input.kot.floorCode,
    sectionCode: input.kot.sectionCode,
    orderTypeCode: input.kot.orderTypeCode,
    diningTypeCode: input.kot.diningTypeCode,
    waiterCode: input.kot.waiterCode,
    captainCode: input.kot.captainCode,
    guestCount: input.kot.guestCount,
    kotDocNo: input.kot.docNo,
    status: input.status,
    subTotal: input.totals.subTotal,
    discountPercentage: 0,
    discountAmount: input.totals.discountAmount,
    totalDiscAmountPer: input.totals.discountAmount,
    taxAmount: input.totals.taxAmount,
    additionalCharge: 0,
    roundingAmount: 0,
    netTotal: input.totals.netTotal,
    paidAmount,
    balanceAmount: Math.max(0, round(input.totals.netTotal - paidAmount)),
    changeAmount: Math.max(0, round(paidAmount - input.totals.netTotal)),
    promotionCode: null,
    promotionDiscountAmount: 0,
    // Coupon Support isn't wired into the restaurant KOT/table-billing flow
    // in this pass — plain retail sales only (lib/pos/mappers.ts).
    couponCode: null,
    couponDiscountAmount: 0,
    isSO: false,
    salesReturn: false,
    billType: "S",
    details: input.details,
    paymentDetails: input.payments.map(paymentToDetailDto),
    serviceDetails: [],
  };
}

/** Builds the CreatePosDto for settling a table's whole KOT as one bill. */
export function buildSettleBillDto(input: {
  kot: KotDto;
  payments: PosPayment[];
  terminalId: string;
  shiftNo?: number | null;
  /** "Held" parks the bill (partial/no payment) against the table instead of completing the sale. */
  status?: PosStatus;
}): CreatePosDto {
  const lines = kotToCartLines(input.kot);
  const details = lines.map((line) => detailFromCartLine(input.kot, line));
  const totals = calcBillTotals(lines, 0);
  return assemblePosDto({
    kot: input.kot,
    details,
    totals,
    payments: input.payments,
    terminalId: input.terminalId,
    shiftNo: input.shiftNo,
    status: input.status ?? "Completed",
  });
}

/**
 * Splits `total` into `ways` shares that sum back to round(total, 2) exactly
 * — the first ways-1 shares are each round(total/ways), the last absorbs
 * whatever rounding remainder is left. Used for the "split evenly" method.
 */
export function partitionAmount(total: number, ways: number): number[] {
  const rounded = round(total);
  const shares: number[] = [];
  let remaining = rounded;
  for (let i = 0; i < ways - 1; i++) {
    const share = round(total / ways);
    shares.push(share);
    remaining = round(remaining - share);
  }
  shares.push(remaining);
  return shares;
}

/** Split Bill (by item): one CreatePosDto per guest, built from that guest's assigned lines only. */
export function buildByItemSplitDtos(input: {
  kot: KotDto;
  /** lineId (KOT detail id) -> 0-based guest index */
  assignment: Record<string, number>;
  guestCount: number;
  /** payments[i] = tenders collected for guest i */
  payments: PosPayment[][];
  terminalId: string;
  shiftNo?: number | null;
}): CreatePosDto[] {
  const allLines = kotToCartLines(input.kot);
  return Array.from({ length: input.guestCount }, (_, guestIdx) => {
    const guestLines = allLines.filter((l) => input.assignment[l.lineId] === guestIdx);
    const details = guestLines.map((line) => detailFromCartLine(input.kot, line));
    const totals = calcBillTotals(guestLines, 0);
    return assemblePosDto({
      kot: input.kot,
      details,
      totals,
      payments: input.payments[guestIdx] ?? [],
      terminalId: input.terminalId,
      shiftNo: input.shiftNo,
      status: "Completed",
    });
  });
}

/**
 * Split Bill (evenly): `ways` identical CreatePosDtos, each carrying every
 * original line at its own share of that line's gross/discount/tax. Builds
 * each split's detail rows directly from partitioned amounts rather than
 * round-tripping through a scaled PosCartLine + calcLineTotals — that would
 * risk a double-rounding mismatch (a scaled unit price that doesn't
 * recompute back to the intended gross share) and could make the N splits'
 * netTotals fail to sum exactly to the original bill.
 */
export function buildEvenSplitDtos(input: {
  kot: KotDto;
  ways: number;
  payments: PosPayment[][];
  terminalId: string;
  shiftNo?: number | null;
}): CreatePosDto[] {
  const allLines = kotToCartLines(input.kot);
  const perLineShares = allLines.map((line) => {
    const t = calcLineTotals(line);
    const kotLine = input.kot.details.find((d) => d.id === line.lineId);
    return {
      line,
      kotRowID: kotLine?.rowID,
      gross: partitionAmount(t.gross, input.ways),
      discount: partitionAmount(t.discount, input.ways),
      tax: partitionAmount(t.tax, input.ways),
    };
  });

  return Array.from({ length: input.ways }, (_, splitIdx) => {
    const details: CreatePosDetDto[] = perLineShares.map(({ line, kotRowID, gross, discount, tax }) => {
      const g = gross[splitIdx] ?? 0;
      const d = discount[splitIdx] ?? 0;
      const tx = tax[splitIdx] ?? 0;
      return {
        itemCode: line.itemCode,
        name: line.name,
        unitCode: line.unitCode,
        unitPrice: line.quantity > 0 ? round(g / line.quantity) : line.unitPrice,
        quantity: line.quantity,
        weighingQuantity: 0,
        grossAmount: g,
        discountPerc: 0,
        discountAmt: d,
        promotionCode: null,
        promotionDiscountAmount: 0,
        amount: round(g - d),
        taxPercentage: line.taxPercentage,
        taxAmount: tx,
        netAmount: round(g - d + tx),
        iac: 0,
        costAmount: 0,
        kotDocNo: input.kot.docNo,
        kotRowID,
      };
    });
    const subTotal = round(details.reduce((sum, dtl) => sum + dtl.grossAmount, 0));
    const discountAmount = round(details.reduce((sum, dtl) => sum + dtl.discountAmt, 0));
    const taxAmount = round(details.reduce((sum, dtl) => sum + dtl.taxAmount, 0));
    const netTotal = Math.max(0, round(subTotal - discountAmount + taxAmount));
    return assemblePosDto({
      kot: input.kot,
      details,
      totals: { subTotal, discountAmount, taxAmount, netTotal },
      payments: input.payments[splitIdx] ?? [],
      terminalId: input.terminalId,
      shiftNo: input.shiftNo,
      status: "Completed",
    });
  });
}

